"""Economics/Pricing Agent: Evaluates margin limits and historical sales data stored in MySQL to propose revised prices."""

import logging
import os
from typing import Dict, Any, Optional
import mysql.connector
from datetime import datetime

logger = logging.getLogger(__name__)

# --- Database helper ---

def get_db_connection():
    return mysql.connector.connect(
        host=os.getenv("MYSQL_HOST", "localhost"),
        port=int(os.getenv("MYSQL_PORT", "3306")),
        user=os.getenv("MYSQL_USER", "root"),
        password=os.getenv("MYSQL_PASSWORD", "your_password"),
        database=os.getenv("MYSQL_DATABASE", "price_optimization"),
    )


def get_historical_prices(asin: str, days: int = 30) -> List[Dict[str, Any]]:
    """Fetch historical price data for an ASIN from MySQL."""
    conn = get_db_connection()
    cursor = conn.cursor(dictionary=True)
    try:
        from datetime import timedelta
        start_date = (datetime.utcnow() - timedelta(days=days)).strftime("%Y-%m-%d")
        cursor.execute(
            "SELECT price, date_recorded, margin_percent FROM competitor_price_history WHERE asin = %s AND date_recorded >= %s ORDER BY date_recorded DESC LIMIT %s",
            (asin, start_date, days),
        )
        rows = cursor.fetchall()
        return rows
    finally:
        cursor.close()
        conn.close()


def compute_recommended_price(
    asin: str,
    current_price: float,
    min_margin_percent: float = 18.0,
    target_margin_percent: float = 20.0,
) -> Optional[Dict[str, Any]]:
    """
    Compute a revised price based on historical data and margin constraints.
    Returns a dict with suggested_price, projected_margin, confidence, or None.
    """
    history = get_historical_prices(asin, days=60)
    if not history:
        logger.warning(f"No historical data for {asin}; returning None.")
        return None

    # Simple average of last prices
    avg_historical = sum(p["price"] for p in history) / len(history)
    # Compute suggested price to hit target margin given a cost base.
    # For demo, assume cost is current_price * (1 - target_margin/100)
    # In practice, you'd have a cost table.
    cost_estimate = current_price * (1 - target_margin_percent / 100.0)
    if cost_estimate <= 0:
        return None

    # Desired price = cost / (1 - target_margin/100)
    suggested_price = cost_estimate / (1 - target_margin_percent / 100.0)

    # Ensure margin does not drop below minimum
    if current_price > 0:
        projected_margin = ((suggested_price - cost_estimate) / suggested_price) * 100
        if projected_margin < min_margin_percent:
            # Adjust suggested price to respect minimum margin
            # price = cost / (1 - min_margin/100)
            suggested_price = cost_estimate / (1 - min_margin_percent / 100.0)
            projected_margin = min_margin_percent

    confidence = min(len(history) / 30.0, 1.0)  # simple confidence based on data volume

    return {
        "asin": asin,
        "current_price": current_price,
        "suggested_price": round(suggested_price, 2),
        "projected_margin": round(projected_margin, 2),
        "confidence": round(confidence, 2),
        "historical_average": round(avg_historical, 2),
        "note": "Generated by Economics/Pricing Agent",
    }


if __name__ == "__main__":
    import sys, json
    asin = sys.argv[1] if len(sys.argv) > 1 else "B0XYZ123"
    current = float(sys.argv[2]) if len(sys.argv) > 2 else 29.99
    result = compute_recommended_price(asin, current)
    if result:
        print(json.dumps(result, indent=2))
    else:
        print("No recommendation computed.")